const nomes = ['João', 'Maria', 'José', 'João', 'Pedro', 'Ana'];

const nomesOrdenados = nomes.toSorted(); // alfabética (Unicode)
console.log('Original: ', nomes); // ['Ana', 'José', 'João', 'João', 'Maria', 'Pedro']
console.log('Ordenado: ', nomesOrdenados); // ['Ana', 'José', 'João', 'João', 'Maria', 'Pedro']